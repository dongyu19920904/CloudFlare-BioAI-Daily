- 用来源中真实的疑问、对比或研究细节引起兴趣，不编悬念，不让“值得关注”代替解释。读完应能复述一项发现、理解一个概念，并知道原文还可看什么；不是只知道“有进展，但还需验证”。
- 不写“临床管线布局、转化潜力、多组学范式、基案假设”等研究汇报式套话；用具体动作讲清变化。不能编“你马上就能用”的好处，也不把通俗化写成夸张营销。
